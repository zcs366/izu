all_sentences = L1_SIMPLE + L2_NESTED + L3_CONTEXT + L4_REASONING
labels = (['L1']*len(L1_SIMPLE) + ['L2']*len(L2_NESTED) + 
          ['L3']*len(L3_CONTEXT) + ['L4']*len(L4_REASONING))

print(f"加载 ModernBERT-base...")
model = SentenceTransformer("answerdotai/ModernBERT-base", device=DEVICE)
print(f"编码 {len(all_sentences)} 句...")
emb = model.encode(all_sentences, normalize_embeddings=True)
FULL_DIM = emb.shape[1]
print(f"Shape: {emb.shape}\n")

# ─── 逐层实验 ─────────────────────────────────────
print(f"{'═'*60}")
print(f"语义复杂度 × d×r=常数")
print(f"{'═'*60}")

for level in ['L1', 'L2', 'L3', 'L4']:
    mask = [l == level for l in labels]
    data = emb[mask]
    n = len(data)
    
    pca = PCA(n_components=min(FULL_DIM, n))
    pca.fit(data)
    
    def cos_at_d(d):
        d = min(d, pca.n_components_)
        c = pca.transform(data)[:,:d]
        r = c @ pca.components_[:d] + pca.mean_
        nr = np.linalg.norm(r, axis=1, keepdims=True); nr[nr==0]=1
        r /= nr
        return np.mean(np.sum(data*r, axis=1))
    
    # 找D₀
    lo, hi = 8, min(FULL_DIM, n)
    D0 = hi
    while lo <= hi:
        mid = ((lo+hi)//2//8)*8; mid = max(8, mid)
        if cos_at_d(mid) >= TARGET_COS:
            D0 = mid; hi = mid - 8
        else: lo = mid + 8
    
    print(f"\n  {level}: {n}句, D₀={D0}")
    
    d_list = sorted(set(d for d in [D0, D0//2, D0//4, D0//8] if d >= 4), reverse=True)
    print(f"  {'d':>4s} {'r':>3s} {'d×r':>5s} {'cos':>7s}")
    print(f"  {'-'*22}")
    
    c_vals = []
    for d in d_list:
        r = int(np.ceil(D0 / d))
        total = r * d
        cos_v = cos_at_d(min(total, min(FULL_DIM, n)))
        c_vals.append(total)
        print(f"  {d:4d} {r:3d} {total:5d} {cos_v:7.4f}")
    
    print(f"  C = {np.mean(c_vals):.1f} ± {np.std(c_vals):.1f}")

